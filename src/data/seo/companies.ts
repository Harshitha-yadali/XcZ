export function getCompanyBySlug(slug: string): ResumeCompany | undefined {
  return RESUME_COMPANIES.find((company) => company.slug === slug);
}

export function getRelatedCompanies(company: ResumeCompany, limit = 4): ResumeCompany[] {
  return RESUME_COMPANIES.filter((c) => c.type === company.type && c.slug !== company.slug).slice(0, limit);
}
