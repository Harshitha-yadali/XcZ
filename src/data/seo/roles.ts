export function getRoleBySlug(slug: string): ResumeRole | undefined {
  return RESUME_ROLES.find((role) => role.slug === slug);
}

export function getRolesByCategory(category: string): ResumeRole[] {
  return RESUME_ROLES.filter((role) => role.category === category);
}

export function getRelatedRoles(role: ResumeRole, limit = 4): ResumeRole[] {
  return RESUME_ROLES.filter((r) => r.category === role.category && r.slug !== role.slug).slice(0, limit);
}
